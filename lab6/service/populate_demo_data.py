def get_or_create_admin():
    user, created = User.objects.get_or_create(
        username=ADMIN_LOGIN,
        defaults={'email': ADMIN_EMAIL, 'is_staff': True, 'is_superuser': True})
    if created:
        user.set_password(ADMIN_PASSWORD)
        user.save()
        print('создан суперпользователь', ADMIN_LOGIN)
    return user


def main():
    admin = get_or_create_admin()

    for name in COUNTRIES:
        Country.objects.get_or_create(name=name)
    for name, desc in MACHINE_TYPES:
        MachineType.objects.get_or_create(name=name, defaults={'description': desc})
    for name, country in BRANDS:
        Brand.objects.get_or_create(name=name,
                                    defaults={'country': Country.objects.get(name=country)})
    for name, city in ENTERPRISES:
        Enterprise.objects.get_or_create(name=name, defaults={'city': city})
    for name, days, cost in REPAIR_TYPES:
        RepairType.objects.get_or_create(name=name,
                                         defaults={'duration_days': days, 'cost': cost})
    for inv, mtype, brand, year, ent in MACHINES:
        Machine.objects.get_or_create(
            inventory_no=inv,
            defaults={'machine_type': MachineType.objects.get(name=mtype),
                      'brand': Brand.objects.get(name=brand),
                      'release_year': year,
                      'enterprise': Enterprise.objects.get(name=ent)})

    for inv, rtype, start, end, comment in REPAIRS:
        Repair.objects.get_or_create(
            machine=Machine.objects.get(inventory_no=inv),
            start_date=start,
            defaults={'repair_type': RepairType.objects.get(name=rtype),
                      'end_date': end,
                      'comment': comment,
                      'author': admin})

    print('стран: %d, типов: %d, марок: %d, предприятий: %d, станков: %d, '
          'видов ремонта: %d, ремонтов: %d' % (
              Country.objects.count(), MachineType.objects.count(),
              Brand.objects.count(), Enterprise.objects.count(),
              Machine.objects.count(), RepairType.objects.count(),
              Repair.objects.count()))


if __name__ == '__main__':
    main()
